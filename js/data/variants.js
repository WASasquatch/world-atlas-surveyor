// Pick a variant index from the rng, then merge variant overrides
// onto the base palette to produce the final palette object.
//
// forceVariantName (optional): when provided, look up the matching variant
//   by exact name and use it regardless of RNG. Used by the easter-egg seed
//   system to lock specific named worlds (Vulcan, Bajor, etc.) to their
//   intended palette.
//
// Easter-egg variants — those flagged with _easterEgg: true — are filtered
// OUT of the random pool. They can only be selected via forceVariantName.
// This keeps named-world palettes (Vulcan, Klingon, etc.) reserved for
// their seeds while still allowing the regular variants to roll freely.
function pickPalette(type, rng, forceVariantName) {
  const allVariants = TYPE_VARIANTS[type] || [{ name: 'Standard' }];
  const base = PALETTES[type] || {};

  // Force-variant lookup wins over RNG.
  if (forceVariantName) {
    const forced = allVariants.find(v => v.name === forceVariantName);
    if (forced) {
      const merged = Object.assign({}, base, forced);
      merged._variantName = forced.name;
      return merged;
    }
    // Fall through to random pick if name didn't resolve (shouldn't happen).
  }

  // Random pick from non-easter-egg variants only.
  const pool = allVariants.filter(v => !v._easterEgg);
  const variants = pool.length > 0 ? pool : allVariants;
  const idx = Math.floor(rng() * variants.length);
  const variant = variants[idx];
  const merged = Object.assign({}, base, variant);
  merged._variantName = variant.name || 'Standard';
  return merged;
}

export { TYPE_VARIANTS, pickPalette };
